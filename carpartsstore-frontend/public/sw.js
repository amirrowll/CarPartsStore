// Self-cleaning and unregistering Service Worker for Pinpart Store
// Eliminates stale chunk caching and "Failed to fetch dynamically imported module" errors

self.addEventListener('install', () => {
  self.skipWaiting();
});

self.addEventListener('activate', (event) => {
  event.waitUntil(
    caches.keys().then((keys) => {
      return Promise.all(keys.map((k) => caches.delete(k)));
    }).then(() => {
      return self.registration.unregister();
    })
  );
});